ORDER = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ-:>/"


def tile(rows):
    t = [[0] * 8 for _ in range(8)]
    for y, row in enumerate(rows.split()):
        for x, ch in enumerate(row):
            if ch == "1":
                t[y][x + 1] = 1
    out = [r[:] for r in t]
    for y in range(8):
        for x in range(8):
            if not t[y][x] and any(0 <= y + dy < 8 and 0 <= x + dx < 8 and t[y + dy][x + dx]
                                   for dy in (-1, 0, 1) for dx in (-1, 0, 1)):
                out[y][x] = 3
    p0 = [sum(((out[y][x] & 1) << (7 - x)) for x in range(8)) for y in range(8)]
    p1 = [sum(((out[y][x] >> 1) << (7 - x)) for x in range(8)) for y in range(8)]
    return p0 + p1


def main():
    from PIL import Image
    root = Path(__file__).resolve().parents[2]
    img = Image.new("RGB", (len(ORDER) * 9, 8), (60, 120, 200))
    colors = {1: (255, 255, 255), 3: (0, 0, 0)}
    for i, ch in enumerate(ORDER):
        t = tile(G[ch])
        for y in range(8):
            for x in range(8):
                v = ((t[y] >> (7 - x)) & 1) | (((t[8 + y] >> (7 - x)) & 1) << 1)
                if v:
                    img.putpixel((i * 9 + x, y), colors[v])
    out = root / "build" / "video" / "font_preview.png"
    out.parent.mkdir(parents=True, exist_ok=True)
    img.resize((img.width * 4, img.height * 4), Image.NEAREST).save(out)
    print(f"書き出しました: {out}")

if __name__ == "__main__":
    main()
